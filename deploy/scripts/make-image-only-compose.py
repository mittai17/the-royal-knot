#!/usr/bin/env python3
"""Generate deploy/docker-compose.images.yml: docker-compose.yml with every `build:` block removed.

Use it where Dokploy has no source tree to build from (Compose type "Raw"): build the images first
(`docker compose build`), then paste/upload the generated file. Images are referenced by tag, so the
Docker daemon Dokploy deploys to must already have them (or pull them from a private registry).
"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "docker-compose.yml").read_text().splitlines(keepends=True)
out, skip = [], False
for line in src:
    if re.match(r"^    build:", line):
        skip = "block" if line.rstrip().endswith("build:") else "inline"
        if skip == "inline":
            skip = False
        continue
    if skip == "block":
        if line.startswith("      "):
            continue
        skip = False
    out.append(line)
dest = root / "deploy" / "docker-compose.images.yml"
dest.write_text("# GENERATED by deploy/scripts/make-image-only-compose.py - do not edit.\n" + "".join(out))
print("wrote", dest)
